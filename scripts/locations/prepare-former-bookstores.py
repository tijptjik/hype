"""Compile the reviewed historical bookstore layer into deterministic D1 SQL.

Only generates a migration; never opens or writes a database. Building evidence is
pinned in fixtures/former-bookstores.json. Re-run after reviewing that fixture.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = Path(__file__).with_name('fixtures') / 'former-bookstores.json'


def encoded(value):
    """Serialize stable UTF-8 JSON for SQL values and content hashes."""
    return json.dumps(value, ensure_ascii=False, separators=(',', ':'))


def quoted(value):
    """Quote SQLite values without interpreting source text as SQL."""
    if value is None:
        return 'NULL'
    return "'" + str(value).replace("'", "''") + "'"


def digest(value):
    """Hash the exact immutable JSON payload being persisted."""
    return hashlib.sha256(encoded(value).encode()).hexdigest()


def generate():
    """Generate atomic-runner SQL with a completion receipt and fail-closed guards."""
    data = json.loads(FIXTURE.read_text())
    migration = data['migration']
    owner = data['organisationId']
    expected_ids = sorted(row['featureId'] for row in data['records'])
    if not expected_ids or len(expected_ids) != len(set(expected_ids)) or expected_ids != data['expectedFeatureIds']:
        raise ValueError('Fixture must contain the complete unique reviewed layer cohort')
    count = len(expected_ids)
    sql = [f'-- Generated by scripts/locations/prepare-former-bookstores.py.\n'
           '-- Complete reviewed historical layer; run in one transaction / D1 migration. No network at apply time.\n'
           '-- Preserve intangible status, Feature map pins and original legacy evidence.\n'
           '-- Scope: spec/breadline/proposal/drafts/location-address-occupancy.md\n'
           'CREATE TABLE _former_books_guard (valid INTEGER NOT NULL CHECK(valid=1));',
           'CREATE TABLE _former_books_pending (featureId TEXT PRIMARY KEY);']
    receipt = f"NOT EXISTS(SELECT 1 FROM revisionChangeSet WHERE id={quoted(migration)})"
    for row in data['records']:
        sql.append(f"INSERT INTO _former_books_pending SELECT {quoted(row['featureId'])} WHERE {receipt};")
    sql.append(f"INSERT INTO _former_books_guard SELECT CASE WHEN NOT ({receipt}) OR "
               f"(SELECT count(*) FROM feature f JOIN _former_books_pending p ON p.featureId=f.id "
               f"WHERE f.projectId={quoted(data['projectId'])} AND f.organisationId={quoted(owner)} "
               f"AND f.layerId={quoted(data['layerId'])} AND f.isIntangible=1 AND f.isDraft=0 "
               f"AND f.currentRevisionId IS NOT NULL AND NOT EXISTS(SELECT 1 FROM featureLocation fl WHERE fl.featureId=f.id))={count} THEN 1 ELSE 0 END;")

    # New layer members must not be silently omitted; only explicitly reviewed exclusions are allowed.
    # A five-row pilot receipt is not a layer receipt.
    exclusions = ','.join(quoted(fid) for fid in data.get('excludedFeatureIds', [])) or "''"
    sql.append(f"INSERT INTO _former_books_guard SELECT CASE WHEN NOT ({receipt}) OR (SELECT count(*) FROM feature WHERE layerId={quoted(data['layerId'])} AND id NOT IN ({exclusions}))={count} THEN 1 ELSE 0 END;")
    revision_ids = ','.join(quoted('former-bookstore:' + fid + ':feature-v1') for fid in expected_ids)
    sql.append(f"INSERT INTO _former_books_guard SELECT CASE WHEN {receipt} OR (SELECT count(*) FROM featureRevision WHERE changeSetId={quoted(migration)} AND id IN ({revision_ids}))={count} THEN 1 ELSE 0 END;")

    def guard(condition):
        sql.append('INSERT INTO _former_books_guard SELECT CASE WHEN NOT EXISTS(SELECT 1 FROM _former_books_pending) OR (' + condition + ') THEN 1 ELSE 0 END;')

    def insert(table, values, condition='1'):
        columns = ','.join(values)
        literals = ','.join(
            f"(SELECT geometry FROM feature WHERE id={quoted(values['featureId'])})"
            if table == 'featureLocation' and key == 'acceptedGeometry'
            else quoted(v) if not isinstance(v, int) else str(v)
            for key, v in values.items())
        sql.append(f'INSERT INTO {table} ({columns}) SELECT {literals} WHERE EXISTS(SELECT 1 FROM _former_books_pending) AND ({condition});')

    def baseline(location_id, kind, names, geometry, content, provenance, reuse=False, displays=None):
        revision_id = location_id + ':former-books-v1'
        address = {'status': 'unresolved', 'address2dId': None, 'address3dId': None,
                   'address3dUnitId': None, 'snapshotId': None, 'rawSource': {},
                   'fallbackDisplay': {}, 'authored': content}
        if displays:
            address['displayOverrides'] = displays
        facts = {'schemaVersion': 1, 'kind': kind, 'common': {'names': names, 'location': {'geometry': geometry, 'address': address}},
                 'details': {'brands': [], 'operatingStatus': 'permanently_closed'} if kind == 'establishment' else {}}
        condition = f'NOT EXISTS(SELECT 1 FROM location WHERE id={quoted(location_id)})' if reuse else '1'
        if reuse:
            guard(f"NOT EXISTS(SELECT 1 FROM location WHERE id={quoted(location_id)}) OR EXISTS(SELECT 1 FROM location l JOIN locationRevision r ON r.locationId=l.id WHERE l.id={quoted(location_id)} AND l.kind='building' AND l.state='unresolved' AND json_extract(r.rawSource,'$.buildingSource.id')={quoted(provenance['buildingSource']['id'])})")
        insert('location', {'id': location_id, 'kind': kind, 'ownerOrganisationId': owner, 'state': 'unresolved'}, condition)
        insert('locationRevision', {'id': revision_id, 'locationId': location_id, 'version': 1, 'origin': 'local',
                                   'contentHash': digest(provenance), 'rawSource': encoded(provenance), 'facts': encoded(facts)},
               f'NOT EXISTS(SELECT 1 FROM locationRevision WHERE locationId={quoted(location_id)})' if reuse else '1')
        return revision_id, address

    for row in data['records']:
        fid = row['featureId']
        original = (f"json(f.geometry)=json({quoted(encoded(row['expectedGeometry']))}) "
                    f"AND json(f.addressMeta)=json({quoted(encoded(row['expectedAddressMeta']))}) "
                    f"AND json_extract(f.addressMeta,'$.address.legacy.i18n.en.addressProperties.rawAddress')={quoted(row['rawAddress'])}")
        current = row.get('reviewedCurrentState')
        preserved = (f"json(f.geometry)=json({quoted(encoded(current['geometry']))}) "
                     f"AND json(f.addressMeta)=json({quoted(encoded(current['addressMeta']))})") if current else '0'
        # Accept only the original evidence or the exact reviewed editor state, never arbitrary drift.
        guard(f"EXISTS(SELECT 1 FROM feature f JOIN featureRevision r ON r.id=f.currentRevisionId WHERE f.id={quoted(fid)} "
              f"AND (({original}) OR ({preserved})) "
              "AND r.sequence=f.revisionVersion AND json_extract(r.content,'$.placement.location') IS NULL "
              "AND json_extract(r.content,'$.detachedBrands') IS NULL AND json(json_extract(r.content,'$.placement.addressMeta'))=json(f.addressMeta))")
        for locale, name in row['names'].items():
            guard(f'EXISTS(SELECT 1 FROM featureI18n WHERE featureId={quoted(fid)} AND locale={quoted(locale)} AND title={quoted(name)})')
        bid = None
        if row['building']:
            b = row['building']
            # Match the shared building importer identity; private importer identities are not reused.
            bid = 'building:' + digest(['building-export', None, 'shared', b['id']])
            names = {k.lower(): v for k, v in b['names'].items() if v}
            if not names:
                names = {'und': b['name']} if b.get('name') else {'en': row['buildingLabel']}
            labels = b['addresses']['addresses'][0]['display'] if len(b['addresses']['addresses']) == 1 else {'en': row['buildingLabel']}
            content = {'scope': 'building', 'i18n': {k: {'formattedAddress': v} for k, v in labels.items()}, 'unit': None, 'unitI18n': {}}
            baseline(bid, 'building', names, {'type': 'Point', 'coordinates': b['points']['coordinates']}, content,
                     {'kind': 'building-export-baseline', 'buildingSource': {'id': b['id'], 'release': data['exportRelease']},
                      'migration': migration, 'evidence': b, 'attribution': data['attribution']}, reuse=True)
        lid = 'former-bookstore:' + fid
        aid = lid + ':address'
        arid = aid + ':v1'
        oid = lid + ':occupancy:v1'
        provenance = {'migration': migration, 'featureId': fid, 'originalAddress': row['rawAddress'],
                      'buildingDisposition': row['buildingDisposition'], 'buildingReason': row['buildingReason'],
                      **({'apolloConfirmation': data['apolloConfirmation']} if fid == '8Blj7NBdhCzc' else {}), 'evidencePolicy': data['evidencePolicy']}
        # Preserve the complete original English input (including ambiguous bare unit tokens).
        displays = {locale: row['rawAddress'] for locale in row['names']}
        rid, address = baseline(lid, 'establishment', row['names'], row['expectedGeometry'], row['content'], provenance, displays=displays)
        insert('address', {'id': aid, 'sourceKey': encoded({'provider': 'hype', 'family': 'former-bookstore', 'id': fid})})
        insert('addressRevision', {'id': arid, 'addressId': aid, 'scope': row['content']['scope'], 'components': encoded(row['content']),
                                  'geometry': None, 'contentHash': digest(row['content']), 'sourceReferences': '[]', 'rawSource': encoded(provenance)})
        evidence = encoded([{'source': {'kind': 'record', 'resourceType': 'locationRevision', 'revisionId': rid},
                             'supports': ['former-occupancy', 'address'], 'quotedText': row['rawAddress'],
                             'description': data['evidencePolicy'], 'sourceDate': None}])
        insert('locationAddress', {'id': aid+':relation', 'relationshipId': aid+':relation', 'scopeOrganisationId': owner,
                                  'locationId': lid, 'addressRevisionId': arid, 'addressState': 'former', 'evidence': evidence, 'provenance': encoded(provenance)})
        insert('locationOccupancy', {'id': oid, 'relationshipId': oid, 'scopeOrganisationId': owner,
                                    'establishmentLocationId': lid, 'containerLocationId': bid, 'addressRevisionId': arid,
                                    'occupancyState': 'former', 'evidence': evidence, 'provenance': encoded(provenance)})
        binding = {'locationId': lid, 'associationVersion': migration, 'factsRevisionId': rid, 'locationRevisionId': rid,
                   'acceptedOverrides': {}, 'factsOrganisationRevision': None, 'locationOrganisationRevision': None,
                   'occupancyRevisionId': oid, 'addressRevisionId': arid, 'membershipRevisionIds': [], 'placementOverrides': {},
                   'acceptedGeometry': row['expectedGeometry'], 'acceptancePolicy': None, 'acceptanceProposalId': None,
                   'memberships': [{'containerLocationId': bid, 'role': 'building', 'bindingVersion': migration,
                                    'occupancyRevisionId': oid, 'membershipRevisionId': None}] if bid else []}
        insert('featureRevisionWriteScope', {'featureId': fid, 'token': migration})
        # Transform only this revision's placement and address displays; keep all unrelated content.
        expr = f"json_set(r.content,'$.placement.location',json({quoted(encoded(binding))}),'$.placement.addressMeta.address.source',json({quoted(encoded(address))}))"
        for locale in row['names']:
            expr = f"json_set({expr},'$.translations.\"{locale}\".address.value',{quoted(displays[locale])},'$.translations.\"{locale}\".address.generated',json('false'))"
        # Reviewed editor content keeps its address and translations; attach only historical occupancy.
        if current:
            kept = f"json_set(r.content,'$.placement.location',json_set(json({quoted(encoded(binding))}),'$.acceptedGeometry',json(f.geometry)))"
            expr = f"CASE WHEN {preserved} THEN {kept} ELSE {expr} END"
        # The changeset is inserted before any revision, then used as the successful-run receipt.
        sql.append(f"INSERT INTO revisionChangeSet(id,actorId,origin,reason,createdAt) SELECT {quoted(migration)},'migration:former-bookstores','migration','historical bookstore layer former occupancies',strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE EXISTS(SELECT 1 FROM _former_books_pending) AND NOT EXISTS(SELECT 1 FROM revisionChangeSet WHERE id={quoted(migration)});")
        new_revision = lid+':feature-v1'
        sql.append(f"INSERT INTO featureRevision(id,featureId,previousRevisionId,changeSetId,content,recordState,sequence) SELECT {quoted(new_revision)},f.id,r.id,{quoted(migration)},{expr},r.recordState,f.revisionVersion+1 FROM feature f JOIN featureRevision r ON r.id=f.currentRevisionId JOIN _former_books_pending p ON p.featureId=f.id WHERE f.id={quoted(fid)};")
        insert('featureLocation', {'featureId': fid, 'locationId': lid, 'factsRevisionId': rid, 'locationRevisionId': rid,
                                   'version': migration, 'acceptedOverrides': '{}', 'occupancyRevisionId': oid, 'addressRevisionId': arid,
                                   'acceptedGeometry': encoded(row['expectedGeometry'])})
        sql.append(f"UPDATE feature SET addressMeta=json_extract((SELECT content FROM featureRevision WHERE id={quoted(new_revision)}),'$.placement.addressMeta'),currentRevisionId={quoted(new_revision)},revisionVersion=revisionVersion+1,modifiedAt=strftime('%Y-%m-%dT%H:%M:%fZ','now') WHERE id={quoted(fid)} AND id IN (SELECT featureId FROM _former_books_pending);")
        for locale in row['names']:
            preserve_filter = f" AND NOT EXISTS(SELECT 1 FROM feature f WHERE f.id={quoted(fid)} AND ({preserved}))" if current else ''
            sql.append(f"UPDATE featureI18n SET displayAddress={quoted(displays[locale])},displayAddressGen=0 WHERE featureId={quoted(fid)} AND locale={quoted(locale)} AND featureId IN (SELECT featureId FROM _former_books_pending){preserve_filter};")
        sql.append(f"DELETE FROM featureRevisionWriteScope WHERE featureId={quoted(fid)} AND token={quoted(migration)};")
    sql += ['DROP TABLE _former_books_pending;', 'DROP TABLE _former_books_guard;']
    return '\n\n'.join(sql) + '\n'


if __name__ == '__main__':
    output = ROOT / 'migrations/0207_former_bookstore_occupancy.sql'
    output.write_text(generate())
    print(output)
