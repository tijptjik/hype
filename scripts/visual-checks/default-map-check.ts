import { chromium } from 'playwright'
const b = await chromium.launch({headless:true,args:['--disable-web-security']})
const p = await b.newPage({viewport:{width:1400,height:1000}})
p.on('console',m=>{if(m.type()==='error' && !m.text().includes('Vite') && !m.text().includes('WebSocket')) console.log('ERROR',m.text())})
p.on('response',async r=>{if(r.url().includes('/_app/remote/') && /getDefaultLayerResources|getResourcePage|getPinnedResource|getFeaturePage/.test(r.url())) console.log('RESPONSE',r.url().split('?')[0],(await r.text()).slice(0,500))})
await p.goto('http://127.0.0.1:4173',{waitUntil:'domcontentloaded'})
await p.waitForTimeout(15000)
await p.getByRole('button',{name:'Settings',exact:true}).click()
await p.waitForTimeout(1000)
console.log('BODY',await p.locator('body').innerText())
console.log('SWITCHES', await p.getByRole('switch').evaluateAll(es => es.map(e => ({name:e.getAttribute('name'), checked:e.getAttribute('aria-checked')}))))
const mapSwitch = p.getByRole('switch').filter({visible:true}).last()
await mapSwitch.click()
await p.waitForTimeout(2000)
console.log('SAVED',await mapSwitch.getAttribute('aria-checked'))
await p.reload({waitUntil:'domcontentloaded'})
await p.waitForTimeout(10000)
await p.getByRole('button',{name:'Settings',exact:true}).click()
console.log('RELOADED_SWITCHES', await p.getByRole('switch').evaluateAll(es => es.map(e => ({name:e.getAttribute('name'), checked:e.getAttribute('aria-checked')}))))
console.log('BUTTONS',await p.getByRole('button').evaluateAll(es=>es.map(e=>({text:e.textContent,label:e.getAttribute('aria-label'),title:e.getAttribute('title')}))))
await p.screenshot({path:'output/playwright/default-before.png'})
await b.close()
