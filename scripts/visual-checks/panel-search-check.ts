import { chromium } from 'playwright'
const browser = await chromium.launch({ executablePath: '/home/io/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome', args: ['--disable-web-security'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const errors: string[] = []
page.on('pageerror', e => errors.push(e.message))
await page.route('**/__star-check.html', route => route.fulfill({ contentType: 'text/html', body: '<html data-theme="hype-light"><head><script>globalThis.__sveltekit_dev={env:{}}</script><script type="module" src="/@vite/client"></script></head><body><div id="app"></div><script type="module" src="/src/tests/fixtures/panelSearchCheck.ts"></script></body></html>' }))
await page.goto('http://127.0.0.1:4173/__star-check.html')
await page.getByRole('button', {name:'Want to visit (5)', exact:true}).waitFor()
await page.screenshot({path:'output/playwright/stars-light.png'})
const search = page.getByRole('searchbox').first()
await search.fill('Jumbo')
if (await page.getByRole('button', {name:'Jumbo', exact:true}).count() !== 2) throw Error('Search result missing')
await search.press('Escape')
await page.getByRole('button', {name:'Want to visit (5)',exact:true}).click()
await page.waitForTimeout(300)
if (await page.getByRole('searchbox').count() !== 1) throw Error('Collapse failed')
await page.getByRole('button', {name:'Ah Yuen Tailor Factory',exact:true}).click()
if (await page.locator('[data-opened]').textContent() !== 'visited-9') throw Error('Open failed')
await page.getByRole('button', {name:'Want to visit (5)',exact:true}).click()
await page.evaluate(() => document.documentElement.setAttribute('data-theme','hype-dark'))
await page.locator('#right-panel > div').evaluate(e => e.scrollTop = 0)
await page.waitForTimeout(350)
await page.screenshot({path:'output/playwright/stars-dark.png'})
await page.setViewportSize({width:1280,height:900})
await page.screenshot({path:'output/playwright/stars-desktop.png'})
console.log(JSON.stringify({errors, horizontalOverflow:await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)}))
await browser.close()
