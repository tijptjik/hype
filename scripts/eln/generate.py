"""Generate the reviewed ELN content migration; never connect to a live database."""
import json
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROJECT = 'vGBvWfSZNELM'
LAYERS = {2024: 'lvWu_dCwiVZt', 2025: '0bf1RYWdpaAt', 2026: 'vli8hfmD-XEZ', 2027: 'zJJawV9ay56p'}
PROPERTIES = {'country': 'j608565AMXfN', 'synopsis': 'ZkXV20T2Bsa7', 'author': 'PLifDO417BbU', 'authorBio': 'w7L3$qPA41ij', 'performer': 'Wvsnoy64ilyJ', 'performerBio': 'K0ceBm5NQFlF', 'host': 'eln2024HostProp'}
EXTRA = {'isbn': 'ISBN', 'publicationDate': 'Published', 'awards': 'Awards', 'nominationStatus': 'Nomination / availability notes'}
INTERNAL = {'isbn'}
TRANS = {'synopsis', 'authorBio', 'performerBio'}
COUNTRIES = dict(zip(['Germany','Czechia','France','Finland','Hungary','Italy','Ireland','The Netherlands','Spain','Ukraine','Belgium'], ['c8g3m0$7Bin8','fB6nseLK9k71','97u0sJB8WjKr','oNX7m$EI2QAc','SEvRA5ti17R7','80W3pCYC5vQx','KLMt4Zr$ia4p','ifnFW4WRxNhD','F08sWnOJ5hX9','Am5$Z1oqwaa7','eln2025CountryBE']))
COUNTRIES.update({'Portugal': 'eln2025CountryPT', 'Switzerland': 'eln2025CountryCH', 'Poland': 'eln2025CountryPL'})


def quote(value):
    """Return a SQL literal without interpolating unescaped source content."""
    return 'NULL' if value is None else "'" + str(value).replace("'", "''") + "'"


def generate():
    """Build deterministic, gap-only SQL with strict target identity checks."""
    data = json.loads((ROOT / 'scripts/eln/data/backfill.json').read_text())
    out = ['-- Generated by python scripts/eln/generate.py; sources: scripts/eln/data/backfill.json.',
           '-- Content only. Upload covers and apply the separately generated image SQL afterwards.',
           '-- New 2027 nominations are drafts at the organiser-requested provisional venue.',
           'PRAGMA foreign_keys=ON;',
           'CREATE TABLE _eln_backfill_guard (ok INTEGER NOT NULL CHECK(ok = 1));']
    emit = out.append
    emit(f"INSERT INTO _eln_backfill_guard SELECT count(*)=4 FROM layer WHERE projectId={quote(PROJECT)} AND id IN ({','.join(map(quote,LAYERS.values()))});")
    emit("INSERT INTO _eln_backfill_guard SELECT count(*)=1 FROM feature WHERE id='elnBook00004' AND projectId='vGBvWfSZNELM' AND layerId='vli8hfmD-XEZ' AND json_extract(geometry,'$.coordinates[0]')=114.1551177 AND json_extract(geometry,'$.coordinates[1]')=22.2804411 AND spatialIndex IS NOT NULL;")
    for r in data['books']:
        if r['edition'] != 2027 and not r.get('newHistorical'):
            emit(f"INSERT INTO _eln_backfill_guard SELECT count(*)=1 FROM feature WHERE id={quote(r['id'])} AND projectId={quote(PROJECT)} AND layerId={quote(LAYERS[r['edition']])};")
    emit("-- A text biography must not silently discard classifier assignments.")
    emit("INSERT INTO _eln_backfill_guard SELECT NOT EXISTS(SELECT 1 FROM propertyValue WHERE propertyId='K0ceBm5NQFlF');")
    emit("UPDATE property SET type='specifier', component='TextareaField' WHERE id='K0ceBm5NQFlF' AND projectId='vGBvWfSZNELM';")
    emit("INSERT INTO propertyValue(id,propertyId,value) VALUES('eln2025CountryPL','j608565AMXfN','Poland') ON CONFLICT DO NOTHING;")
    emit("INSERT INTO propertyValueI18n(propertyValueId,locale,value) VALUES('eln2025CountryPL','en','Poland') ON CONFLICT DO NOTHING;")
    # The organiser confirmed this omitted entry; the venue listing supplies its map point.
    spatial = json.loads((ROOT/'scripts/eln/data/poland-spatial.json').read_text())
    emit("INSERT INTO _eln_backfill_guard SELECT NOT EXISTS(SELECT 1 FROM feature WHERE id='eln2025Book013' AND (projectId<>'vGBvWfSZNELM' OR layerId<>'0bf1RYWdpaAt'));")
    emit(f"INSERT INTO feature(id,organisationId,projectId,layerId,contributorId,geometry,spatialIndex,isPublished) SELECT 'eln2025Book013',organisationId,projectId,'0bf1RYWdpaAt',contributorId,{quote(spatial['geometry'])},{quote(json.dumps(spatial))},0 FROM feature WHERE id='eln2025Book001' ON CONFLICT DO NOTHING;")
    emit("INSERT INTO featureI18n(featureId,locale,title,titleGen,descriptionGen,displayAddress,displayAddressGen,addressProperties) VALUES('eln2025Book013','en','Poems New and Collected',0,0,'Ztoryhome, G/F, 118 Queen’s Road West, Sheung Wan',0,'{}') ON CONFLICT DO NOTHING;")
    for rank,(key,label) in enumerate(EXTRA.items(),10):
        pid = 'eln_' + key
        PROPERTIES[key] = pid
        public = int(key not in INTERNAL)
        component = 'InputField' if key in {'isbn', 'publicationDate'} else 'TextareaField'
        emit(f"INSERT INTO property(id,projectId,scope,type,key,component,isTranslatable,isUserContributable,isDefaultEnabled) VALUES ({quote(pid)},{quote(PROJECT)},'project','specifier',{quote(key)},{quote(component)},0,{public},{public}) ON CONFLICT(id) DO NOTHING;")
        emit(f"INSERT INTO _eln_backfill_guard SELECT count(*)=1 FROM property WHERE id={quote(pid)} AND projectId={quote(PROJECT)} AND key={quote(key)} AND type='specifier';")
        emit(f"INSERT INTO projectProperty(projectId,propertyId,isEnabled,isDefaultEnabled,rank) VALUES({quote(PROJECT)},{quote(pid)},1,{public},{rank}) ON CONFLICT DO NOTHING;")
        emit(f"INSERT INTO propertyI18n(propertyId,locale,label,labelGen,placeholder,placeholderGen) SELECT {quote(pid)},'en',{quote(label)},0,'',0 WHERE NOT EXISTS(SELECT 1 FROM propertyI18n WHERE propertyId={quote(pid)} AND locale='en');")
    emit('-- Enable the supported fields on every edition without duplicating layer assignments.')
    for lid in LAYERS.values():
        for key, pid in PROPERTIES.items():
            public = int(key not in INTERNAL)
            emit(f"UPDATE layerProperty SET isVisible={public},isUserContributable={public} WHERE layerId={quote(lid)} AND propertyId={quote(pid)};")
            emit(f"INSERT INTO layerProperty(layerId,propertyId,isVisible,isUserContributable) SELECT {quote(lid)},{quote(pid)},{public},{public} WHERE NOT EXISTS(SELECT 1 FROM layerProperty WHERE layerId={quote(lid)} AND propertyId={quote(pid)});")

    def prop(fid,key,value):
        """Fill only absent values, preserving non-empty editorial content."""
        pid=PROPERTIES[key]
        if key in ('country','host'):
            pv=COUNTRIES[value] if key=='country' else value
            emit(f"INSERT INTO featureProperty(featureId,propertyId,propertyValueId) VALUES({quote(fid)},{quote(pid)},{quote(pv)}) ON CONFLICT(featureId,propertyId) DO UPDATE SET propertyValueId=excluded.propertyValueId WHERE featureProperty.propertyValueId IS NULL AND coalesce(trim(featureProperty.value),'')='';")
        elif key in TRANS:
            emit(f"INSERT INTO featureProperty(featureId,propertyId) VALUES({quote(fid)},{quote(pid)}) ON CONFLICT DO NOTHING;")
            emit(f"INSERT INTO featurePropertyI18n(featureId,propertyId,locale,value,valueGen) VALUES({quote(fid)},{quote(pid)},'en',{quote(value)},0) ON CONFLICT(featureId,propertyId,locale) DO UPDATE SET value=excluded.value,valueGen=0 WHERE coalesce(trim(featurePropertyI18n.value),'')='';")
        else:
            if key == 'publicationDate':
                value = value[:4]
            emit(f"INSERT INTO featureProperty(featureId,propertyId,value) VALUES({quote(fid)},{quote(pid)},{quote(value)}) ON CONFLICT(featureId,propertyId) DO UPDATE SET value=excluded.value WHERE coalesce(trim(featureProperty.value),'')='' AND featureProperty.propertyValueId IS NULL;")

    # Copy the known Wyndham point and its matching H3 index; never inherit place identity.
    new = [r for r in data['books'] if r['edition']==2027]
    new += [dict(id='eln2027Slot'+str(i+1).zfill(2),title=country,country=country,nominationStatus='Book and performer to be confirmed; Wyndham Social is provisional.') for i,country in enumerate(data['placeholders'])]
    emit('-- Abort on deterministic-ID collisions outside the intended layer.')
    for r in new:
        fid=r['id']
        emit(f"INSERT INTO _eln_backfill_guard SELECT NOT EXISTS(SELECT 1 FROM feature WHERE id={quote(fid)} AND (projectId<>{quote(PROJECT)} OR layerId<>{quote(LAYERS[2027])}));")
        emit(f"INSERT INTO feature(id,organisationId,projectId,layerId,contributorId,geometry,spatialIndex,addressMeta,isPublished,isPendingReview,isArchived,isIntangible,isVisitable) SELECT {quote(fid)},organisationId,projectId,{quote(LAYERS[2027])},contributorId,geometry,spatialIndex,addressMeta,0,0,0,0,1 FROM feature WHERE id='elnBook00004' AND projectId={quote(PROJECT)} ON CONFLICT(id) DO NOTHING;")
        emit(f"INSERT INTO featureI18n(featureId,locale,title,titleGen,descriptionGen,displayAddress,displayAddressGen,addressProperties) VALUES({quote(fid)},'en',{quote(r['title'])},0,0,'Wyndham Social, G/F, 33 Wyndham Street, Central',0,'{{}}') ON CONFLICT DO NOTHING;")
        if 'coverKey' not in r:
            prop(fid,'country',r['country']);prop(fid,'nominationStatus',r['nominationStatus'])
    for r in data['books']:
        emit(f"-- {r['edition']}: {r['title']} | {r['sources'][0]}")
        for key in PROPERTIES:
            if key in r:
                prop(r['id'],key,r[key])
        emit(f"UPDATE featureI18n SET description={quote(r['synopsis'])},descriptionGen=0 WHERE featureId={quote(r['id'])} AND locale='en' AND coalesce(trim(description),'')='';")
        if r['edition']==2024:
            host={ 'Germany':'eln2024Host001','Czechia':'eln2024Host002','Italy':'eln2024Host003','France':'eln2024Host004'}[r['country']]
            prop(r['id'],'host',host)
    emit('-- Remove the numbered spot prefixes from the four exact seeded titles.')
    for n, title in enumerate(['Kairos', 'The Lake', 'My Stupid Intentions', 'Dear Dickhead'], start=1):
        emit(f"UPDATE featureI18n SET title={quote(title)} WHERE featureId={quote(f'eln2024Spot{n:03}')} AND locale='en' AND title={quote(f'Spot {n} - {title}')};")
    emit('-- Correct only the exact seeded typos; retain subsequent editorial changes.')
    emit("UPDATE featureI18n SET title='The Alaska Sanders Affair' WHERE featureId='eln2025Book011' AND locale='en' AND title='The Alaska Sanders Affairs';")
    emit("UPDATE featureProperty SET value='Nataliia Prysiazhniuk' WHERE featureId='eln2025Book012' AND propertyId='Wvsnoy64ilyJ' AND value='Nataliia Prysiazhniukiuk';")
    for locale,old,newlabel in [('en',"Sep '26","Feb '26"),('zh-hans','2026年9月','2026年2月'),('zh-hant','26年9月','26年2月')]:
        emit(f"UPDATE layerI18n SET nameShort={quote(newlabel)} WHERE layerId='vli8hfmD-XEZ' AND locale={quote(locale)} AND nameShort={quote(old)};")
    # Publish completed editions and restore their descendants; keep the next edition private.
    style_id = hashlib.sha1(b'map-style:noclit25').hexdigest()[:12]
    emit(f"INSERT INTO mapStyles(id,code) VALUES({quote(style_id)},'noclit25') ON CONFLICT(code) DO NOTHING;")
    for locale in ['en', 'zh-hant', 'zh-hans']:
        emit(f"INSERT INTO mapStyleI18n(mapStyleId,locale,name,nameGen,descriptionGen) SELECT id,{quote(locale)},'NocLit''25',0,0 FROM mapStyles WHERE code='noclit25' ON CONFLICT DO NOTHING;")
    emit(f"INSERT INTO projectMapStyles(projectId,mapStyleId) SELECT {quote(PROJECT)},id FROM mapStyles WHERE code='noclit25' ON CONFLICT(projectId) DO UPDATE SET mapStyleId=excluded.mapStyleId;")
    actor = "'qJpgD5f5wBMvvvLFbUOPnFfSpRiUXdaM'"
    publication = f"isPublished=1,localIsPublished=NULL,publishedAt=coalesce(publishedAt,strftime('%Y-%m-%dT%H:%M:%fZ','now')),publisherId=coalesce(publisherId,{actor})"
    emit(f"UPDATE project SET {publication},markerStyleCode='flag' WHERE id={quote(PROJECT)};")
    for year, lid in LAYERS.items():
        if year == 2027:
            emit(f"UPDATE layer SET isPublished=0,localIsPublished=NULL,publishedAt=NULL,publisherId=NULL,metadata=json_set(coalesce(metadata,'{{}}'),'$.markerStyleCode','flag') WHERE id={quote(lid)} AND projectId={quote(PROJECT)};")
        else:
            emit(f"UPDATE layer SET {publication},metadata=json_set(coalesce(metadata,'{{}}'),'$.markerStyleCode','flag','$.mapStyleCode','noclit25') WHERE id={quote(lid)} AND projectId={quote(PROJECT)};")
            emit(f"UPDATE feature SET {publication} WHERE layerId={quote(lid)} AND projectId={quote(PROJECT)};")
    emit('DROP TABLE _eln_backfill_guard;')
    (ROOT/'migrations/0127_eln_sourced_backfill.sql').write_text('\n'.join(out)+'\n')


if __name__ == '__main__':
    generate()
