/** Abort a stale or incompatible snapshot before any permanent writes.
 * @param condition SQL predicate. @param description Human-readable guard purpose. @returns Nothing.
 */
function guard(condition: string, description: string): void {
  sql.push(
    `-- ${description}`,
    `INSERT INTO _donor_naming_guard SELECT CASE WHEN (${condition}) THEN 1 ELSE 0 END WHERE ${enabled};`,
  )
}
