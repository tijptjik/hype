/** Quote a SQLite literal, including apostrophes in authored names.
 * @param value Scalar or JSON object. @returns SQL literal with no interpolation execution.
 */
function literal(value: unknown): string {
  if (value == null) return 'NULL'
  if (typeof value === 'number') return String(value)
  return `'${(typeof value === 'string' ? value : JSON.stringify(value)).replaceAll("'", "''")}'`
}
/** Obtain an explicitly named CLI argument.
 * @param name Argument flag. @returns Required argument value.
 */
function argument(name: string): string {
  const index = process.argv.indexOf(name)
  if (index < 0 || !process.argv[index + 1]) throw new Error(`Required: ${name}`)
  return process.argv[index + 1]
}
