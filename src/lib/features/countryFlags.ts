for (const code of codes) {
  names.set(code, code)
  try {
    const label = (display.of(code.toUpperCase()) ?? '').toLowerCase()
    // Historical aliases (such as FX for France) must not replace a canonical match.
    if (label && !names.has(label)) names.set(label, code)
  } catch {
    /* Non-ISO asset aliases only match their code. */
  }
}
