/**
 * Resolves country-property labels or ISO codes to bundled flags.
 * @param value Country label; joint entries may use ampersands, commas or slashes.
 * @returns Unique asset codes; unknown values produce no invented flag.
 */
export function countryFlagCodes(value: string): string[] {
  const normalized = value.trim().toLowerCase()
  const whole = names.get(normalized)
  if (whole) return [whole]
  return [
    ...new Set(
      normalized.split(/\s*(?:&|,|\/|\band\b)\s*/).flatMap(part => {
        const code = names.get(part)
        return code ? [code] : []
      }),
    ),
  ].slice(0, 4)
}
