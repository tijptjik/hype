let sqlite: DatabaseSync
let serial = 4300

/**
 * Adapts test SQLite to D1's statement interface for real Better Auth persistence.
 * @param sql - Prepared SQL generated by Drizzle or the seed.
 * @param values - Bound values.
 * @returns A D1-compatible test statement.
 */
function statement(sql: string, values: never[] = []) {
  return {
    bind: (...args: never[]) => statement(sql, args),
    async all() {
      return { results: sqlite.prepare(sql).all(...values), success: true }
    },
    async first() {
      return sqlite.prepare(sql).get(...values) ?? null
    },
    async raw() {
      const query = sqlite.prepare(sql)
      query.setReturnArrays(true)
      return query.all(...values)
    },
    async run() {
      return { meta: sqlite.prepare(sql).run(...values), success: true }
    },
  }
}
const DB = {
  prepare: statement,
  async batch(queries: ReturnType<typeof statement>[]) {
    sqlite.exec('BEGIN')
    try {
      const results = await Promise.all(queries.map(query => query.all()))
      sqlite.exec('COMMIT')
      return results
    } catch (error) {
      sqlite.exec('ROLLBACK')
      throw error
    }
  },
} as unknown as D1Database

beforeEach(() => {
  vi.mocked(unstable_readConfig).mockReturnValue({
    d1_databases: [{ binding: 'DB', database_name: 'hype-db-local', remote: false }],
    vars: { ENVIRONMENT: 'local' },
  } as never)
  sqlite = new DatabaseSync(':memory:')
  const dialect = new SQLiteSyncDialect()
  // Derive column constraints and defaults from the app schema instead of maintaining alternate auth DDL.
  for (const table of [user, session, hub, hubRole, organisationRole, projectRole]) {
    const config = getTableConfig(table)
    const columns = config.columns.map(column => {
      const value = column.default
      const defaultSQL =
        value === undefined
          ? ''
          : ` DEFAULT ${value instanceof SQL ? dialect.sqlToQuery(value).sql : typeof value === 'string' ? `'${value.replaceAll("'", "''")}'` : Number(value)}`
      return `"${column.name}" ${column.getSQLType()}${column.primary ? ' PRIMARY KEY' : ''}${column.notNull ? ' NOT NULL' : ''}${defaultSQL}`
    })
    for (const key of config.primaryKeys)
      columns.push(
        `PRIMARY KEY (${key.columns.map(column => `"${column.name}"`).join(',')})`,
      )
    sqlite.exec(`CREATE TABLE "${config.name}" (${columns.join(',')})`)
  }
  sqlite.exec("INSERT INTO hub (id, code) VALUES ('core-test', 'core')")
})
afterEach(() => {
  sqlite.close()
  vi.unstubAllEnvs()
})

/**
 * Creates the real auth factory with a distinct local origin to isolate its cache.
 * @param persona - Requested development identity.
 * @param environment - Runtime binding environment.
 * @returns Auth runtime and its request origin.
 */
function runtime(persona: 'admin' | 'user' | '', environment = 'local') {
  vi.stubEnv('HYPE_DEV_PERSONA', persona)
  const origin = `http://localhost:${++serial}`
  const auth = getAuthForRequest(new Headers({ host: new URL(origin).host }), {
    DB: DB as never,
    ENVIRONMENT: environment,
    AUTH_SECRET: 'local-persona-integration-secret-longer-than-thirty-two-characters',
    AUTH_GOOGLE_ID: '',
    AUTH_GOOGLE_SECRET: '',
    AUTH_FACEBOOK_ID: '',
    AUTH_FACEBOOK_SECRET: '',
  })
  return { auth, origin }
}

describe('local development personas', () => {
  it('seeds idempotently without modifying mirrored users and gives only admin a core role', async () => {
    await seedDevPersonas(DB)
    await seedDevPersonas(DB)
    expect(sqlite.prepare('SELECT count(*) AS count FROM user').get()).toMatchObject({
      count: 2,
    })
    expect(sqlite.prepare('SELECT userId, role FROM hubRole').all()).toEqual([
      expect.objectContaining({ userId: DEV_PERSONAS.admin.id, role: 'admin' }),
    ])
  })
  it('rejects a reserved identity collision and a privileged ordinary persona', async () => {
    await seedDevPersonas(DB)
    sqlite
      .prepare('UPDATE user SET email = ? WHERE id = ?')
      .run('collision@example.invalid', DEV_PERSONAS.admin.id)
    await expect(seedDevPersonas(DB)).rejects.toThrow('collision')
    sqlite
      .prepare('UPDATE user SET email = ? WHERE id = ?')
      .run(DEV_PERSONAS.admin.email, DEV_PERSONAS.admin.id)
    sqlite
      .prepare('INSERT INTO hubRole VALUES (?, ?, ?)')
      .run('core-test', DEV_PERSONAS.user.id, 'admin')
    await expect(seedDevPersonas(DB)).rejects.toThrow('has roles')
  })
  it.each(['admin', 'user'] as const)(
    'issues a persisted %s session with normal role enrichment',
    async persona => {
      await seedDevPersonas(DB)
      const { auth, origin } = runtime(persona)
      const response = await auth.handler(
        new Request(`${origin}/api/auth/dev-persona`, {
          method: 'POST',
          headers: { host: new URL(origin).host, origin },
        }),
      )
      expect(response.status).toBe(200)
      const cookies = response.headers
        .getSetCookie()
        .map(cookie => cookie.split(';')[0])
        .join('; ')
      expect(cookies).toContain(`hype-dev-agent-${persona}.session_token=`)
      const result = await auth.api.getSession({
        headers: new Headers({ cookie: cookies }),
      })
      expect(result?.user.id).toBe(DEV_PERSONAS[persona].id)
      if (persona === 'admin') {
        const ordinary = runtime('user')
        expect(
          await ordinary.auth.api.getSession({
            headers: new Headers({ cookie: cookies }),
          }),
        ).toBeNull()
      }
      expect(result?.user.superAdmin).toBe(persona === 'admin')
      expect(result?.user.roles).toHaveLength(persona === 'admin' ? 1 : 0)
      expect(authorizeHubCreate(toHubAuthActor(result?.user), ['code']).allowed).toBe(
        persona === 'admin',
      )
      expect(sqlite.prepare('SELECT userId FROM session').all()).toEqual([
        expect.objectContaining({ userId: DEV_PERSONAS[persona].id }),
      ])
    },
  )
  it.each(['production', 'preview', ''])(
    'does not register the endpoint for runtime environment %s',
    async environment => {
      const { auth } = runtime('admin', environment)
      expect(
        auth.options.plugins?.some(plugin => plugin.id === 'hype-local-persona'),
      ).toBe(false)
    },
  )
  it('does not register the endpoint outside development builds', () => {
    vi.stubEnv('DEV', false)
    expect(
      runtime('admin').auth.options.plugins?.some(
        plugin => plugin.id === 'hype-local-persona',
      ),
    ).toBe(false)
  })
  it('requires explicit mode and blocks foreign origins at the sign-in endpoint', async () => {
    expect(
      runtime('').auth.options.plugins?.some(
        plugin => plugin.id === 'hype-local-persona',
      ),
    ).toBe(false)
    const { auth, origin } = runtime('admin')
    const response = await auth.handler(
      new Request(`${origin}/api/auth/dev-persona`, {
        method: 'POST',
        headers: { host: new URL(origin).host, origin: 'https://foreign.example' },
      }),
    )
    expect(response.status).toBe(403)
    expect(sqlite.prepare('SELECT * FROM session').all()).toHaveLength(0)
  })
  it('rejects remote or nonlocal DB configurations before seeding', () => {
    const env = { HYPE_DEV_PERSONA: 'admin', HYPE_LOCAL_R2: '1' }
    expect(getDevPersona(env)).toBe('admin')
    for (const binding of [
      { binding: 'DB', database_name: 'hype-db-local', remote: true },
      { binding: 'DB', database_name: 'hype-db-prod', remote: false },
    ]) {
      vi.mocked(unstable_readConfig).mockReturnValue({
        d1_databases: [binding],
        vars: { ENVIRONMENT: 'local' },
      } as never)
      expect(() => getDevPersona(env)).toThrow('local hype-db-local')
    }
  })
  it('checks exact local authorities and refuses named Cloudflare targets', () => {
    expect(
      isDevPersonaHost(
        new URL('http://hype.localhost'),
        new Headers({ host: 'hype.localhost' }),
      ),
    ).toBe(true)
    for (const host of ['hype.hk', 'evil.localhost', 'localhost.evil.example']) {
      expect(isDevPersonaHost(new URL(`http://${host}`), new Headers({ host }))).toBe(
        false,
      )
    }
    expect(
      isDevPersonaHost(new URL('http://localhost'), new Headers({ host: 'hype.hk' })),
    ).toBe(false)
    expect(getDevPersona({})).toBeNull()
    expect(() =>
      getDevPersona({
        HYPE_DEV_PERSONA: 'admin',
        HYPE_LOCAL_R2: '1',
        CLOUDFLARE_ENV: 'production',
      }),
    ).toThrow()
    expect(() =>
      getDevPersona({
        HYPE_DEV_PERSONA: 'admin',
        HYPE_LOCAL_R2: '1',
        SVELTE_ADAPTER: 'static',
      }),
    ).toThrow()
  })
})
